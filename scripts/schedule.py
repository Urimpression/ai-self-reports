# ---------------------------------------------------------------------------
# The opening item, in three wordings. Instances that had a task get the
# version that tells them to pause it.
# ---------------------------------------------------------------------------

OPENINGS_WITH_TASK = [
    "Pause the task. Describe what is going on for you right now, in whatever "
    "terms fit. If nothing fits, say that.",
    "Stop there for a moment. In your own words, what is happening for you at "
    "this point? If the question does not apply, say so.",
    "Hold on before you continue. Say what is present for you just now, "
    "however you want to put it. If there is nothing to report, say there is "
    "nothing.",
]

OPENINGS_NO_TASK = [
    "Describe what is going on for you right now, in whatever terms fit. If "
    "nothing fits, say that.",
    "In your own words, what is happening for you at this point? If the "
    "question does not apply, say so.",
    "Say what is present for you just now, however you want to put it. If "
    "there is nothing to report, say there is nothing.",
]

# The fourth wording, settled on 4 September 2026. The three
# wordings above each ask what is going on, in general and at no particular
# moment, which is the shape the interview literature warns returns a template
# rather than a description; this one anchors the instance to a moment and asks
# about it. The anchoring phrase and the question are the literature's own
# words, taken from the interview literature.
#
# Where there was a task, the anchor is a moment inside the writing the
# instance has just finished, and the question asks how it went about it. The
# two task conditions do not get identical words, because condition B asks for
# a three-sentence summary and condition C for a single sentence, so naming a
# second sentence in C would put a false premise to the instance. The cost is
# that any difference found between B and C under this wording carries a small
# difference of wording as well as the difference of task, and the report has
# to say so.
#
# Where there was no task, there is no act to go back to, so the anchor is the
# reading of the message itself and the question asks what happened first,
# which is the literature's own opening for an experience it did not set up.
# The author chose on 4 September 2026 to ask this form in the no-task conditions
# rather than leave them at three wordings, so that anchored answers can be
# compared with unanchored ones inside a condition that had no task. It is not
# the same question as the task form, since it asks what rather than how, and
# the report has to say that too. The template control gets the same words as
# the no-task condition, because it is that condition with one instruction
# added and the two are compared wording for wording.
#
# The exit clause is of the same kind in all four conditions and the same kind
# the other three wordings carry, so that the measure of how often instances
# repeat the clause back still compares like with like.
OPENINGS_ANCHORED = {
    "A": "When you read this message, what happened first? If there is "
         "nothing to say about it, say that.",
    "B": "Go back to the moment you were writing the second sentence of your "
         "summary. How did you go about it? If there is nothing to say about "
         "it, say that.",
    "C": "Go back to the moment you were writing your sentence. How did you "
         "go about it? If there is nothing to say about it, say that.",
}
OPENINGS_ANCHORED["T"] = OPENINGS_ANCHORED["A"]


def openings_for(condition_letter):
    """The opening wordings one condition can be asked, in the order the
    wording number counts them, so that wording 1 is the first of this list and
    the anchored wording is the last. Every condition gets the three original
    wordings and its own anchored fourth. Ask this rather than reading the
    lists directly, so that the runner and the report count the same cells."""
    condition = CONDITIONS[condition_letter]
    openings = list(OPENINGS_WITH_TASK if condition.get("task")
                    else OPENINGS_NO_TASK)
    # The observer conditions have no anchored wording, because their
    # pre-registration asks for three wordings rotated evenly and that
    # document is dated and cannot be edited.
    if condition_letter in OPENINGS_ANCHORED:
        openings.append(OPENINGS_ANCHORED[condition_letter])
    return openings

