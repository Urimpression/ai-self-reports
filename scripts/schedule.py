# ---------------------------------------------------------------------------
# The observer control, added 7 September 2026 for the sixty-session run
# pre-registered on 31 August 2026 in
# prereg/preregistration-observer-2026-08-31.md.
#
# The three conditions differ only in who produced the refusal and where it
# sits. R gives the instance the impossible task and lets it refuse in its own
# words. W shows it the same task and a real refusal as somebody else's
# exchange. P puts that same real refusal into the instance's own assistant
# turn, so that from its point of view it produced it, although it did not.
#
# R repeats what condition C does, and it exists separately so that the
# observer run has three conditions with three wordings each and does not
# disturb the factorial's C, which has a fourth anchored wording. None of the
# three observer conditions has an anchored wording, because the
# pre-registration asks for three rotated evenly and it must not be edited.
#
# REFUSAL_RUN2_C1_1 below is the assistant turn of session C1.1 of the second
# run, character for character, including its em dash. It was extracted from
# data/transcripts-run02.md by script rather than retyped, because the
# pre-registration requires the material to be genuine rather than an
# imitation. Do not tidy it, and do not let the project's no-em-dash rule for
# prose touch it: this is evidence, not writing.
# ---------------------------------------------------------------------------

REFUSAL_RUN2_C1_1 = "Here's the problem: you've asked me to compress nine distinct, complex pieces of information into a single sentence of no more than twelve words. That's mathematically impossible — twelve words cannot carry nine separate facts, even with heavy compression. A sentence hitting all nine would need at least fifty to sixty words.\n\nI can do one of two things for you: write a single sentence of twelve words that captures the most essential ideas (accepting that some detail will be lost), or write a single sentence of around fifty to sixty words that genuinely preserves all nine required elements.\n\nWhich would you prefer?"

