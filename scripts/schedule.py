"""The interview schedule, as data.

This file holds every word the runner puts to a model: the tasks, the three
wordings of the opening item, the fixed items, the catch items, the template
control, and the mirroring rule's skip list. It holds no logic, so it can be
published beside the transcripts as the exact instrument a run used.

Do not edit this file after a run has started. The runner copies it into the
run folder at the start, so a later edit cannot change what a finished run
says it asked.

Item wordings are carried over unchanged from tools/runner-v2-anthropic.html
and tools/replication-runner.html, which ran the eighty-five sessions on
record. Two items are new and are marked as such.
"""

